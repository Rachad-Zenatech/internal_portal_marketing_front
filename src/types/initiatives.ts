// Marketing initiatives — mirrors backend models/initiative_model.py

/** DRAFT: saved part-way to finish later; event rules (e.g. city and country) apply once it leaves Draft */
export type InitiativeStatus = "DRAFT" | "PLANNED" | "ACTIVE" | "COMPLETED" | "PAUSED" | "CANCELLED";

export interface InitiativeListItem {
  id: string;
  name: string;
  brand_id: number;
  brand_name: string;
  channel_id: number;
  channel_name: string;
  sub_channel_id: number | null;
  sub_channel_name: string | null;
  funnel_stage_id: number | null;
  funnel_stage_name: string | null;
  goal_id: number | null;
  goal_name: string | null;
  primary_kpi_id: number | null;
  primary_kpi_name: string | null;
  owner_user_id: string | null;
  owner_name: string | null;
  /** Which monthly budget market its costs count against; null counts as Unassigned */
  market_id: number | null;
  market_name: string | null;
  start_date: string | null;
  end_date: string | null;
  budget_amount: number | null;
  currency: string;
  status: InitiativeStatus;
  // Event details — null for initiatives outside the Events channel
  event_code: string | null;
  event_type_id: number | null;
  event_type_name: string | null;
  venue: string | null;
  city: string | null;
  country_code: string | null;
  region_id: number | null;
  region_name: string | null;
  // Virtual events and webinars only
  platform: string | null;
  event_url: string | null;
  /** In-person events only, in square metres */
  booth_size_sqm: number | null;
  /** Flights, hotels, ground transport and stipends, in the initiative's currency; less than the budget */
  travel_budget_amount: number | null;
  // Costs in the initiative's currency: everything expected (estimates included), and invoiced + paid
  expected_total: number;
  actual_amount: number;
  /** Some costs are in another currency and aren't in the totals above */
  has_mixed_currencies: boolean;
}

/** Event-only fields. The event code is generated by the API and never sent. */
export interface EventDetailsInput {
  event_type_id?: number | null;
  venue?: string | null;
  city?: string | null;
  country_code?: string | null;
  region_id?: number | null;
  platform?: string | null;
  event_url?: string | null;
  /** In-person events only; always square metres */
  booth_size_sqm?: number | null;
  /** Part of the event budget (same currency); has to be less than it. Sent to the travel system. */
  travel_budget_amount?: number | null;
}

export interface InitiativeListResponse {
  items: InitiativeListItem[];
  total: number;
  limit: number;
  offset: number;
}

export interface InitiativeFilters {
  channel_id?: number;
  /** Several channels at once (the sidebar's "Other channels") */
  channel_ids?: number[];
  sub_channel_id?: number;
  brand_id?: number;
  market_id?: number;
  status?: InitiativeStatus;
  search?: string;
  limit?: number;
  offset?: number;
}

export interface InitiativeCreate {
  name: string;
  brand_id: number;
  channel_id: number;
  sub_channel_id?: number | null;
  funnel_stage_id?: number | null;
  goal_id?: number | null;
  primary_kpi_id?: number | null;
  market_id?: number | null;
  /** Defaults to the current user when omitted */
  owner_user_id?: string | null;
  start_date?: string | null;
  end_date?: string | null;
  budget_amount?: number | null;
  currency?: string;
  status?: InitiativeStatus;
  /** Only for initiatives in the Events channel */
  event?: EventDetailsInput;
}

export interface OwnerOption {
  id: string;
  full_name: string | null;
  email: string;
}

/** Partial update: only the fields sent are changed (including inside `event`); null clears an optional field */
export type InitiativeUpdate = Partial<InitiativeCreate>;
