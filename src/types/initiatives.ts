// Marketing initiatives — mirrors backend models/initiative_model.py

/** DRAFT: saved part-way to finish later; event rules (e.g. city and country) apply once it leaves Draft */
export type InitiativeStatus = "DRAFT" | "PLANNED" | "ACTIVE" | "COMPLETED" | "PAUSED" | "CANCELLED";

/** Where its results come from: a linked ad or CRM campaign, typed in, or decided later */
export type DataSource = "LINKED" | "MANUAL" | "LATER";

/** External systems a campaign can be linked from */
export type LinkSystem = "HUBSPOT" | "GOOGLE_ADS" | "MICROSOFT_ADS" | "LINKEDIN_ADS" | "META_ADS";

/** An external campaign that belongs to this initiative (one campaign belongs to one initiative) */
export interface InitiativeLink {
  id?: string;
  system: LinkSystem;
  external_id: string;
  account_id: string | null;
}

export interface InitiativeLinkInput {
  system: LinkSystem;
  external_id: string;
  account_id?: string | null;
}

/** Why an initiative needs review */
export type AttentionReason = "OVER_BUDGET" | "NO_BUDGET" | "NO_TRACKING" | "NO_RESULTS" | "NO_DATES";

export type KpiUnit = "COUNT" | "MONEY" | "PERCENT";

/** The optional primary KPI: shown with its target, never used for the worth-it verdict */
export interface PrimaryKpiRef {
  id: number;
  code: string;
  name: string;
  unit: KpiUnit;
}

/** Fields that depend on the channel (see CHANNEL_FIELDS); every one optional */
export type ChannelDetails = Record<string, string | null>;

export interface InitiativeListItem {
  id: string;
  name: string;
  /** Short summary, up to 1000 characters */
  description: string | null;
  brand_id: number;
  brand_name: string;
  channel_id: number;
  channel_name: string;
  sub_channel_id: number | null;
  sub_channel_name: string | null;
  funnel_stage_id: number | null;
  funnel_stage_name: string | null;
  goal_id: number | null;
  goal_name: string | null;
  owner_user_id: string | null;
  owner_name: string | null;
  /** Which monthly budget market its costs count against; null counts as Unassigned */
  market_id: number | null;
  market_name: string | null;
  start_date: string | null;
  end_date: string | null;
  budget_amount: number | null;
  currency: string;
  status: InitiativeStatus;
  primary_kpi_id: number | null;
  primary_kpi: PrimaryKpiRef | null;
  /** Only with a primary KPI; in the KPI's unit */
  kpi_target: number | null;
  data_source: DataSource;
  channel_details: ChannelDetails;
  links: InitiativeLink[];
  /** Invoiced and paid costs in the initiative's currency */
  actual_spend: number;
  /** Actual spend as a share of the budget; null without a positive budget */
  progress_percent: number | null;
  needs_attention: boolean;
  attention_reasons: AttentionReason[];
  // Event details — null for initiatives outside the Events channel
  event_code: string | null;
  event_type_id: number | null;
  event_type_name: string | null;
  venue: string | null;
  city: string | null;
  country_code: string | null;
  region_id: number | null;
  region_name: string | null;
  // Virtual events and webinars only
  platform: string | null;
  event_url: string | null;
  /** In-person events only, in square metres */
  booth_size_sqm: number | null;
  /** Planned travel spend (flights, hotels, ground transport, per diems), in the initiative's currency; less than the budget */
  travel_budget_amount: number | null;
  /** The Navan event its travel bookings come from; null means a Navan event with the same name */
  navan_event_name: string | null;
  /** Navan's estimated travel cost for the event, in its currency: typed in from Navan (its API doesn't share it) */
  navan_estimate_amount: number | null;
  // Costs in the initiative's currency: everything expected (estimates included), and invoiced + paid
  expected_total: number;
  actual_amount: number;
  /** Some costs are in another currency and aren't in the totals above */
  has_mixed_currencies: boolean;
}

/** Event-only fields. The event code is generated by the API and never sent. */
export interface EventDetailsInput {
  event_type_id?: number | null;
  venue?: string | null;
  city?: string | null;
  country_code?: string | null;
  region_id?: number | null;
  platform?: string | null;
  event_url?: string | null;
  /** In-person events only; always square metres */
  booth_size_sqm?: number | null;
  /** Planned travel spend, part of the event budget (same currency); has to be less than it. Navan costs are compared with it. */
  travel_budget_amount?: number | null;
  /** The Navan event its bookings come from, as named in Navan. Empty: a Navan event with the same name. */
  navan_event_name?: string | null;
  /** Navan's estimated travel cost, from its group event page */
  navan_estimate_amount?: number | null;
}

export interface InitiativeListResponse {
  items: InitiativeListItem[];
  total: number;
  limit: number;
  offset: number;
}

export interface InitiativeFilters {
  channel_id?: number;
  /** Several channels at once (the sidebar's "Other channels") */
  channel_ids?: number[];
  sub_channel_id?: number;
  brand_id?: number;
  market_id?: number;
  status?: InitiativeStatus;
  search?: string;
  owner_user_id?: string;
  /** Initiatives whose dates overlap from..to (YYYY-MM-DD) */
  from?: string;
  to?: string;
  /** Only initiatives that need review */
  needs_attention?: boolean;
  limit?: number;
  offset?: number;
}

export interface InitiativeCreate {
  name: string;
  brand_id: number;
  channel_id: number;
  sub_channel_id?: number | null;
  funnel_stage_id?: number | null;
  goal_id?: number | null;
  market_id?: number | null;
  /** Defaults to the current user when omitted */
  owner_user_id?: string | null;
  start_date?: string | null;
  end_date?: string | null;
  budget_amount?: number | null;
  currency?: string;
  status?: InitiativeStatus;
  description?: string | null;
  /** Optional; a KPI target needs one */
  primary_kpi_id?: number | null;
  kpi_target?: number | null;
  data_source?: DataSource;
  channel_details?: ChannelDetails;
  /** Replaces the whole set when sent */
  links?: InitiativeLinkInput[];
  /** Only for new initiatives: the maturity window, prefilled from the sub-channel's default */
  evaluation?: { maturity_days?: number };
  /** Only for initiatives in the Events channel */
  event?: EventDetailsInput;
}

export interface MoneyAmount {
  currency: string;
  amount: number;
}

interface SummaryCounts {
  total: number;
  active: number;
  needs_attention: number;
  /** Sum of the matching initiatives' budgets, per currency */
  allocated_budget: MoneyAmount[];
}

/** GET /api/initiatives/summary: the KPI cards, with the same filters as the list */
export interface InitiativeSummary extends SummaryCounts {
  /** The same period length just before from/to; null without a period */
  previous: SummaryCounts | null;
}

/** One line of an initiative's recent activity, from the audit log */
export interface InitiativeActivity {
  at: string;
  actor_name: string | null;
  title: string;
  detail: string | null;
}

export interface OwnerOption {
  id: string;
  full_name: string | null;
  email: string;
}

/** Partial update: only the fields sent are changed (including inside `event`); null clears an optional field */
export type InitiativeUpdate = Partial<InitiativeCreate>;
