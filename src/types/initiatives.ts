// Marketing initiatives — mirrors backend models/initiative_model.py

export type InitiativeStatus = "PLANNED" | "ACTIVE" | "COMPLETED" | "PAUSED" | "CANCELLED";

export interface InitiativeListItem {
  id: string;
  name: string;
  brand_id: number;
  brand_name: string;
  channel_id: number;
  channel_name: string;
  sub_channel_id: number | null;
  sub_channel_name: string | null;
  funnel_stage_id: number | null;
  funnel_stage_name: string | null;
  goal_id: number | null;
  goal_name: string | null;
  primary_kpi_id: number | null;
  primary_kpi_name: string | null;
  owner_user_id: string | null;
  owner_name: string | null;
  start_date: string | null;
  end_date: string | null;
  budget_amount: number | null;
  currency: string;
  status: InitiativeStatus;
  // Event details — null for initiatives outside the Events channel
  event_code: string | null;
  event_type_id: number | null;
  event_type_name: string | null;
  venue: string | null;
  city: string | null;
  country_code: string | null;
  region_id: number | null;
  region_name: string | null;
}

/** Event-only fields. The event code is generated by the API and never sent. */
export interface EventDetailsInput {
  event_type_id?: number | null;
  venue?: string | null;
  city?: string | null;
  country_code?: string | null;
  region_id?: number | null;
}

export interface InitiativeListResponse {
  items: InitiativeListItem[];
  total: number;
  limit: number;
  offset: number;
}

export interface InitiativeFilters {
  channel_id?: number;
  sub_channel_id?: number;
  brand_id?: number;
  status?: InitiativeStatus;
  search?: string;
  limit?: number;
  offset?: number;
}

export interface InitiativeCreate {
  name: string;
  brand_id: number;
  channel_id: number;
  sub_channel_id?: number | null;
  funnel_stage_id?: number | null;
  goal_id?: number | null;
  primary_kpi_id?: number | null;
  /** Defaults to the current user when omitted */
  owner_user_id?: string | null;
  start_date?: string | null;
  end_date?: string | null;
  budget_amount?: number | null;
  currency?: string;
  status?: InitiativeStatus;
  /** Only for initiatives in the Events channel */
  event?: EventDetailsInput;
}

export interface OwnerOption {
  id: string;
  full_name: string | null;
  email: string;
}

/** Partial update: only the fields sent are changed (including inside `event`); null clears an optional field */
export type InitiativeUpdate = Partial<InitiativeCreate>;
